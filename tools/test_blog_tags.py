#!/usr/bin/env python3
"""Real Estate Tips tag is data-driven: archive.json, pills, and a tag page."""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import blog_tags

ARCHIVE = ROOT / "blogs/real_estate/archive.json"
ARTICLE = ROOT / "blogs/real_estate/two-acres-two-lots.html"
TAG_PAGE = ROOT / "blogs/real_estate/tips.html"
HUB = ROOT / "blogs/real_estate.html"
INDEX = ROOT / "blogs/index.html"
ARCHIVE_JS = ROOT / "blogs/archive.js"
SITEMAP = ROOT / "sitemap.xml"
TAG = "Real Estate Tips"
TAG_URL = "/blogs/real_estate/tips.html"


def fail(msg):
    raise SystemExit("FAIL: " + msg)


data = json.loads(ARCHIVE.read_text(encoding="utf-8"))
meta = data["meta"]
pages = blog_tags.tag_pages(meta)
if not any(p["label"] == TAG and p["path"] == TAG_URL for p in pages):
    fail("archive meta.tagPages must declare Real Estate Tips → /blogs/real_estate/tips.html")
if not any(t.get("id") == "real-estate-tips" and t.get("label") == TAG for t in meta.get("topics") or []):
    fail("archive meta.topics must include real-estate-tips so the hub filter can group these posts")

post = next((p for p in data["posts"] if p["id"] == "two-acres-two-lots"), None)
if not post:
    fail("two-acres is missing from the real estate archive")
if TAG not in (post.get("tags") or []):
    fail("two-acres must be tagged Real Estate Tips in archive.json")
if "real-estate-tips" not in (post.get("topics") or []):
    fail("two-acres must include the real-estate-tips topic")

if not TAG_PAGE.is_file():
    fail("tag page blogs/real_estate/tips.html is missing — run tools/build_blog_hubs.py")
page = TAG_PAGE.read_text(encoding="utf-8")
if TAG not in page or post["title"] not in page:
    fail("tag page must be titled Real Estate Tips and list Two Acres")
if TAG_URL not in page and "two-acres-two-lots.html" not in page:
    fail("tag page must link to the Two Acres post")
if "two-acres-two-lots.html" not in page:
    fail("tag page must link to two-acres-two-lots.html")
if "educational" not in page.lower() or "not financial" not in page.lower():
    fail("tag page must include the educational disclaimer")
if re.search(r'class="[^"]*byline', page, re.I) or 'rel="author"' in page:
    fail("tag page must not have a byline")
if "Generated by tools/blog_tags.py" not in page:
    fail("tag page should be generated from archive.json")

article = ARTICLE.read_text(encoding="utf-8")
if "wl:post-tags:start" not in article or "wl:post-tags:end" not in article:
    fail("two-acres must keep the wl:post-tags marker so pills stay data-driven")
if TAG not in article or TAG_URL not in article:
    fail("two-acres article must show a Real Estate Tips pill that links to the tag page")
# The pill should be a real link, not only a comment
if not re.search(r'<a[^>]+href="' + re.escape(TAG_URL) + r'"[^>]*>\s*Real Estate Tips', article):
    fail("two-acres tag pill must be an <a> to the tag page")

hub = HUB.read_text(encoding="utf-8")
if TAG not in hub or TAG_URL not in hub:
    fail("real estate hub cards must show a Real Estate Tips pill linking to the tag page")
if 'value="real-estate-tips"' not in hub or TAG not in hub:
    fail("real estate hub topic filter must include Real Estate Tips")

index = INDEX.read_text(encoding="utf-8")
if TAG not in index:
    fail("/blogs/ cards must show the Real Estate Tips pill")

js = ARCHIVE_JS.read_text(encoding="utf-8")
if "Real Estate Tips" not in js:
    fail("archive.js TAG map must include Real Estate Tips")
if "tagPages" not in js or "tagPill" not in js:
    fail("archive.js must turn tagPages from the JSON into linked pills")

if TAG_URL.lstrip("/") not in SITEMAP.read_text(encoding="utf-8") and TAG_URL not in SITEMAP.read_text(encoding="utf-8"):
    fail("sitemap.xml must include the Real Estate Tips tag page")

# Shared helper should keep style maps in sync enough to render the new tag.
html = blog_tags.pills_html([TAG], meta, linked=True)
if TAG_URL not in html or TAG not in html:
    fail("blog_tags.pills_html should link Real Estate Tips to its tag page")

print("OK: Real Estate Tips tag is in the archive, on Two Acres, on cards, and at /blogs/real_estate/tips.html")
