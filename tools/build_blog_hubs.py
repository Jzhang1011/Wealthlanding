#!/usr/bin/env python3
"""Build blog section hub pages from their archive.json files.

Each hub (e.g. /blogs/market_investment.html) is rendered from one archive.json using the
same markup contract as /blogs/archive.js, which re-renders the list, filters and search
in the browser. The HTML written here is the static no-JS copy.
Run from the repo root:  python3 tools/build_blog_hubs.py
"""
import html, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SECTIONS = ["blogs/investment/archive.json", "blogs/budget_spending/archive.json", "blogs/real_estate/archive.json"]
TAG = {
    'Tax Strategy': 'bg-emerald-50 text-emerald-800 border-emerald-200',
    'Healthcare': 'bg-amber-50 text-amber-800 border-amber-200',
    'Savings': 'bg-teal-50 text-teal-800 border-teal-200',
    'Family Travel': 'bg-rose-50 text-rose-800 border-rose-200',
    'Markets': 'bg-slate-100 text-slate-800 border-slate-300',
    'Currencies': 'bg-amber-50 text-amber-800 border-amber-200',
    'Healthcare and Biotech': 'bg-teal-50 text-teal-800 border-teal-200',
    'Housing Market': 'bg-orange-50 text-orange-800 border-orange-200',
    'Estate Planning': 'bg-indigo-50 text-indigo-800 border-indigo-200',
    'Case Study': 'bg-blue-50 text-blue-800 border-blue-200',
}
e = lambda s: html.escape(str(s if s is not None else ''), quote=True)


def item(p):
    media = (f'<img src="{e(p["image"])}" alt="{e(p.get("imageAlt",""))}" loading="lazy" class="w-full h-full object-cover aspect-video sm:aspect-[4/3]">'
             if p.get('image') else
             f'<div class="w-full h-full aspect-video sm:aspect-[4/3] bg-slate-900 text-emerald-300 flex items-center justify-center text-xs font-bold uppercase tracking-widest">{e(p.get("tileLabel","Case study"))}</div>')
    tags = ''.join(f'<span class="text-xs font-semibold px-2.5 py-1 rounded-full border {TAG.get(t, TAG["Case Study"])}">{e(t)}</span>' for t in p.get('tags', []))
    return ('<article class="archive-item group flex flex-col sm:flex-row gap-6 py-8 border-b border-slate-200 first:pt-0" '
            f'data-topic="{e(" ".join(p.get("topics", [])))}" data-year="{e(p.get("year",""))}">'
            f'<a href="{e(p["url"])}" class="block w-full sm:w-1/3 lg:w-1/4 shrink-0 overflow-hidden bg-slate-100 rounded-sm" tabindex="-1" aria-hidden="true">{media}</a>'
            '<div class="flex flex-col justify-center">'
            + (f'<div class="text-[11px] font-bold text-emerald-700 uppercase tracking-wide mb-1">{e(p["series"])}</div>' if p.get('series') else '')
            + (f'<div class="text-[11px] font-bold text-slate-500 uppercase tracking-wide mb-2">{e(p["date"])}</div>' if p.get('date') else '')
            + f'<a href="{e(p["url"])}"><h2 class="text-xl sm:text-2xl font-bold text-slate-900 leading-tight mb-3 group-hover:text-emerald-700">{e(p["title"])}</h2></a>'
            f'<p class="text-slate-600 text-sm sm:text-base leading-relaxed line-clamp-3">{e(p["desc"])}</p>'
            f'<div class="mt-4 flex flex-wrap items-center gap-2">{tags}</div></div></article>')


def page(src, data):
    m, posts = data['meta'], data['posts']
    P, hub, title = m['prefix'], m['hub'], m['title']
    used = [t for t in m['topics'] if any(t['id'] in p.get('topics', []) for p in posts)]
    years = sorted({p['year'] for p in posts if p.get('year')}, reverse=True)
    topic_opts = ''.join(f'\n            <option value="{e(t["id"])}">{e(t["label"])}</option>' for t in used)
    year_opts = ''.join(f'\n            <option value="{y}">{y}</option>' for y in years)
    n = len(posts)
    count = f'Showing all {n} article' + ('' if n == 1 else 's')
    items = '\n        '.join(item(p) for p in posts)
    sel = 'w-full bg-slate-50 border border-slate-300 text-slate-700 py-2 pl-3 pr-10 rounded-sm text-sm focus:outline-none focus:border-slate-500 focus:ring-2 focus:ring-emerald-500'
    return f'''<!DOCTYPE html>
<!-- Generated by tools/build_blog_hubs.py from /{src}. Edit the JSON, then re-run the script. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{e(title)} Blog Archive | WealthLanding</title>
  <meta name="description" content="{e(m['description'])}">
  <link rel="canonical" href="https://www.wealthlanding.com/blogs/{hub}">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700;900&display=swap" rel="stylesheet">
  <style>
    :root {{ --emerald: #02B17D; --navy: #0f172a; }}
    body {{ margin: 0; font-family: Inter, system-ui, -apple-system, sans-serif; background: #ffffff; color: var(--navy); }}
    .archive-item {{ transition: all 0.2s ease-in-out; }}
    .archive-item:hover h2 {{ color: var(--emerald); }}
    .archive-item img {{ transition: transform 0.5s ease; }}
    .archive-item:hover img {{ transform: scale(1.03); }}
    select {{
      appearance: none;
      background-image: url("data:image/svg+xml;charset=UTF-8,%3csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='currentColor' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'%3e%3cpolyline points='6 9 12 15 18 9'%3e%3c/polyline%3e%3c/svg%3e");
      background-repeat: no-repeat; background-position: right 1rem center; background-size: 1em;
    }}
  </style>
  <script async src="https://www.googletagmanager.com/gtag/js?id=G-9JMJJ5CJR4"></script>
  <script>
    window.dataLayer = window.dataLayer || [];
    function gtag(){{dataLayer.push(arguments);}}
    gtag('js', new Date());
    gtag('config', 'G-9JMJJ5CJR4');
  </script>
  <script src="https://cdn.tailwindcss.com"></script>
</head>
<body class="antialiased">

  <div id="global-header-target"></div>

  <main class="w-full">
    <section class="bg-slate-50 border-b border-slate-200 py-10 px-4 sm:px-6">
      <div class="max-w-[1000px] mx-auto">
        <nav class="text-sm text-slate-500 mb-3" aria-label="Breadcrumb"><a class="hover:text-emerald-700 underline" href="/blogs/">Blogs</a> <span aria-hidden="true">/</span> {e(title)}</nav>
        <div class="text-sm font-semibold text-emerald-700 uppercase tracking-wider mb-2">Blog Archive</div>
        <h1 class="text-3xl sm:text-4xl font-black tracking-tight text-slate-900 uppercase">{e(title)}</h1>
        <p class="text-slate-600 text-base mt-3 max-w-2xl">{e(m['description'])}</p>
      </div>
    </section>

    <!-- FILTER & SEARCH BAR: wired by /blogs/archive.js -->
    <section class="border-b border-slate-200 bg-white sticky top-0 z-10 shadow-sm px-4 sm:px-6" aria-label="Filter the archive">
      <form class="max-w-[1000px] mx-auto py-4 flex flex-col md:flex-row md:items-center justify-between gap-4" role="search" action="/blogs/{hub}" method="get">
        <div class="flex flex-col sm:flex-row gap-3 w-full md:w-auto">
          <label class="sr-only" for="{P}-filter-topic">Topic</label>
          <select id="{P}-filter-topic" name="topic" class="{sel} sm:w-56">
            <option value="">All Topics</option>{topic_opts}
          </select>
          <label class="sr-only" for="{P}-filter-year">Year</label>
          <select id="{P}-filter-year" name="year" class="{sel} sm:w-32">
            <option value="">All Years</option>{year_opts}
          </select>
        </div>
        <div class="w-full md:w-72 relative">
          <label class="sr-only" for="{P}-search">Search the archive</label>
          <input id="{P}-search" name="q" type="search" autocomplete="off" placeholder="Search archive..." class="w-full bg-white border border-slate-300 text-slate-900 py-2 pl-4 pr-10 rounded-sm text-sm focus:outline-none focus:border-emerald-500 focus:ring-2 focus:ring-emerald-500 placeholder-slate-400">
          <span class="absolute right-3 top-1/2 -translate-y-1/2 text-slate-400 pointer-events-none" aria-hidden="true">
            <svg class="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M21 21l-6-6m2-5a7 7 0 11-14 0 7 7 0 0114 0z"></path></svg>
          </span>
        </div>
      </form>
    </section>

    <!-- ARCHIVE LISTING: posts come from /{src} (static copy below for no-JS) -->
    <section class="max-w-[1000px] mx-auto px-4 sm:px-6 py-8 sm:py-12" aria-labelledby="{P}-archive-h" data-archive-src="/{src}" data-archive-prefix="{P}">
      <h2 id="{P}-archive-h" class="sr-only">All {e(title)} articles</h2>
      <p id="{P}-archive-status" class="text-xs font-semibold text-slate-500 uppercase tracking-wide mb-2" aria-live="polite">{count}</p>
      <div id="{P}-archive-list" class="flex flex-col">
        {items}
      </div>
      <div id="{P}-archive-empty" class="py-12 text-center" hidden>
        <p class="text-lg font-bold text-slate-900">No articles match your filters.</p>
        <p class="text-slate-600 text-sm mt-1">Try a different topic, year or search term.</p>
        <button type="button" id="{P}-archive-reset" class="mt-4 inline-flex items-center text-sm font-bold text-white bg-slate-900 hover:bg-emerald-700 px-4 py-2 rounded-sm">Clear filters</button>
      </div>
    </section>

    <section class="max-w-[1000px] mx-auto px-4 sm:px-6 pb-12">
      <p class="text-xs text-slate-500 leading-relaxed border-t border-slate-200 pt-6"><strong>Disclaimer:</strong> WealthLanding articles are for educational and informational purposes only and are not financial, investment, tax or legal advice. Consult a qualified professional about your own situation.</p>
    </section>
  </main>

  <wealthlanding-footer></wealthlanding-footer>
  <script src="/components/footer.js"></script>
  <script src="/components/header.js"></script>
  <script src="/blogs/archive.js" defer></script>
</body>
</html>
'''


for src in SECTIONS:
    data = json.load(open(os.path.join(ROOT, src), encoding='utf-8'))
    out = os.path.join(ROOT, 'blogs', data['meta']['hub'])
    open(out, 'w', encoding='utf-8').write(page(src, data))
    print('wrote', os.path.relpath(out, ROOT))
